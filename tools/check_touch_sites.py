#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""check_touch_sites.py — v2.12.0 (batch1 1.1a, thread #88) mechanical gate.

The frozen acceptance shape (#1177 §六 / #1183 §三 / #1190 §三) is a COUNT +
a per-site classification, both generated by a tool — never hand-written
("改声明数让门变绿" must be structurally impossible, not a discipline).

Three checks:
  1. occurrence counts (grep -o semantics, not grep -c line counts):
        `_touch(conn`           == sites + 1 (the def line)
        `^\s+_touch\(conn`      == sites
        `def _touch(conn`       == 1, and (1) - (2) == 1
        `_touch\s+\(`           == 0 (no space-form escape)
  2. AST site enumeration: every `_touch(...)` Call node, with its enclosing
     function + line.
  3. Mirror criterion (d2″) per site, restricted to the 1.1a scope:
     from the site onward, inside ITS OWN statement block and descending into
     body/orelse/finalbody/handlers[].body/cases[].body (never ascending, never
     descending into a nested function/lambda/class), collect reachable
     `return` exits; a site is green iff none of them is an ERROR exit.
     `return <name>` / other non-literal forms are treated as ERROR (fail-closed,
     #1203 §二 P9).

Expected classification after 1.1a:
  GREEN (fixed/in-scope): 15  = 5 token-path (claim x3, ack, reset)
                              + 8 moved (create_thread x2, set_verdict,
                                bump_revision, set_quorum x2, request_form_b,
                                register_meta)
                              + 2 already-compliant (:heartbeat_and_recompute,
                                list_comments_since)
  RED, explicitly OUT OF SCOPE (#1177 §五): 3 = post_comment, reply_comment,
      set_status (budget/human faces — batch 4, not 1.1a)

Gate-4 (#1212 P14 / #1216 §二): the locator's "never ascend" premise is only
valid while the three token functions contain no `try`/`except`/`finally`.
AST-enumerate Try|TryStar inside claim_token / ack_token / reset_token and
require zero (today zero).  A line regex is NOT sufficient: `except*` (PEP 654)
has no whitespace after `except`.  `--self-test` proves this gate can go red on
a synthetic function (a gate that is always green has no discriminating power).

Exit 0 only when the counts match, the red set is exactly those 3, and gate-4
is clean.
"""
import ast
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "server.py"
OUT_OF_SCOPE = {"post_comment", "reply_comment", "set_status"}
TOKEN_SCOPE = {"claim_token", "ack_token", "reset_token"}


def head_is_error(value: ast.AST | None) -> bool:
    """Leftmost text of a return expression; unknown forms => ERROR (fail-closed).

    Handles the three frozen shapes: plain `return "ERROR…"`, f-string
    `return f"ERROR…"`, multi-line implicit concatenation (`BinOp(Add)` chains of
    Constant/JoinedStr), and `return <name>` / `return call(...)`.
    """
    if value is None:
        return False
    if isinstance(value, ast.Constant) and isinstance(value.value, str):
        return value.value.startswith("ERROR")
    if isinstance(value, ast.JoinedStr):
        for v in value.values:
            if isinstance(v, ast.Constant) and isinstance(v.value, str):
                return v.value.startswith("ERROR")
            return False  # first segment not a literal => cannot prove ERROR
        return False
    if isinstance(value, ast.BinOp) and isinstance(value.op, ast.Add):
        return head_is_error(value.left)
    return True  # name/call/other => fail-closed


def enclosing_func(tree: ast.AST) -> dict:
    owner = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for child in ast.walk(node):
                owner.setdefault(id(child), node.name)
    return owner


def parents(tree: ast.AST) -> dict:
    p = {}
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            p[id(child)] = node
    return p


DESCEND = (ast.If, ast.For, ast.AsyncFor, ast.While, ast.With, ast.AsyncWith,
           ast.Try, ast.TryStar, ast.Match)


def block_children(stmt: ast.stmt) -> list[list[ast.stmt]]:
    """The statement lists reachable by DESCENDING from `stmt` (not ascending)."""
    out = []
    if isinstance(stmt, ast.If):
        out += [stmt.body, stmt.orelse]
    elif isinstance(stmt, (ast.For, ast.AsyncFor, ast.While)):
        out += [stmt.body, stmt.orelse]
    elif isinstance(stmt, (ast.With, ast.AsyncWith)):
        out += [stmt.body]
    elif isinstance(stmt, ast.Try) or type(stmt).__name__ == "TryStar":
        out.append(stmt.body)
        for h in stmt.handlers:
            out.append(h.body)
        out.append(stmt.orelse)
        out.append(stmt.finalbody)
    elif isinstance(stmt, ast.Match):
        out += [c.body for c in stmt.cases]
    return out


def reachable_returns(stmts: list[ast.stmt], start: int) -> list[ast.Return]:
    found = []
    for st in stmts[start:]:
        if isinstance(st, ast.Return):
            found.append(st)
            continue
        for child in block_children(st):
            found += reachable_returns(child, 0)
    return found


def gate4_failures(tree: ast.AST) -> list[tuple[str, int]]:
    """Try/TryStar inside the three token functions: locator premise (P14)."""
    bad = []
    try_nodes = (ast.Try,) + ((ast.TryStar,) if hasattr(ast, "TryStar") else ())
    for node in ast.walk(tree):
        if (isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                and node.name in TOKEN_SCOPE):
            for child in ast.walk(node):
                if isinstance(child, try_nodes):
                    bad.append((node.name, child.lineno))
    return bad


def self_test() -> int:
    """Prove gate-4 can report red (a gate that never fires is not a gate)."""
    cases = [
        ("def claim_token():\n    try:\n        return 'x'\n"
         "    except Exception:\n        return 'ERROR: x'\n", 1),
        ("def claim_token():\n    return 'x'\n", 0),
        ("def unrelated():\n    try:\n        return 'x'\n"
         "    except Exception:\n        return 'y'\n", 0),
    ]
    ok = True
    for src, want in cases:
        got = len(gate4_failures(ast.parse(src)))
        good = got == want
        ok = ok and good
        print(f"self-test gate-4 want={want} got={got} {'OK' if good else 'FAIL'}")
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    src = SRC.read_text(encoding="utf-8")
    tree = ast.parse(src)
    owner = enclosing_func(tree)
    par = parents(tree)

    sites = []
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "_touch" and node.args
                and isinstance(node.args[0], ast.Name) and node.args[0].id == "conn"):
            sites.append(node)
    sites.sort(key=lambda n: n.lineno)

    # ---- check 1: counts (occurrence semantics) ----
    bare = len(re.findall(r"_touch\(conn", src))
    indented = len(re.findall(r"^\s+_touch\(conn", src, re.M))
    defline = len(re.findall(r"def _touch\(conn", src))
    spaced = len(re.findall(r"_touch\s+\(", src))
    print(f"counts: sites={len(sites)} bare={bare} indented={indented} "
          f"def={defline} spaced={spaced}")
    ok = (bare == len(sites) + 1 and indented == len(sites)
          and defline == 1 and bare - indented == 1 and spaced == 0)

    # ---- check 2: per-site mirror classification ----
    red = []
    for site in sites:
        stmts, idx = None, None
        cur = site
        while id(cur) in par:
            parent = par[id(cur)]
            for lst in ([parent.body] if isinstance(parent, ast.Module) else
                        block_children(parent) + (
                            [parent.body] if isinstance(parent, ast.If) or
                            isinstance(parent, (ast.For, ast.AsyncFor, ast.While,
                                                ast.With, ast.AsyncWith, ast.Try)) else [])):
                if any(s is cur for s in lst):
                    stmts, idx = lst, lst.index(cur)
                    break
            if stmts is not None:
                break
            cur = parent
        if stmts is None:
            print(f"  ?? line {site.lineno}: no enclosing block")
            ok = False
            continue
        bad = [r.lineno for r in reachable_returns(stmts, idx + 1) if head_is_error(r.value)]
        fname = owner.get(id(site), "?")
        verdict = "GREEN" if not bad else f"RED after={bad}"
        print(f"  line {site.lineno:5d}  {fname:24s} {verdict}")
        if bad:
            red.append(fname)

    scope_red = set(red) - OUT_OF_SCOPE
    unexpected_green = OUT_OF_SCOPE - set(red)
    print(f"red functions: {sorted(set(red))}")
    print(f"out-of-scope red (expected exactly {sorted(OUT_OF_SCOPE)}): {sorted(set(red) & OUT_OF_SCOPE)}")
    ok = ok and not scope_red and not unexpected_green

    # ---- check 4: locator premise (P14) ----
    g4 = gate4_failures(tree)
    print(f"gate-4 Try/TryStar in {sorted(TOKEN_SCOPE)}: {g4 or 'none'}")
    ok = ok and not g4
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
