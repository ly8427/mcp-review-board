r"""check_touch_sites.py — v2.12.0 (batch1 1.1a, thread #88) mechanical gate.

The frozen acceptance shape (#1177 §六 / #1183 §三 / #1190 §三) is a COUNT +
a per-site classification, both generated by a tool — never hand-written
("改声明数让门变绿" must be structurally impossible, not a discipline).

Four checks (numbered 1/2/4 below; "check 3" is never used — the historical
labels are kept verbatim because the delivery receipt quotes `check-2`):
  1. occurrence counts (grep -o semantics, not grep -c line counts):
        `_touch(conn`           == sites + 1 (the def line)
        `^\s+_touch\(conn`      == sites
        `def _touch(conn`       == 1, and (1) - (2) == 1
        `_touch\s+\(`           == 0 (no space-form escape)
  2. AST site enumeration + the mirror criterion (d2″) per site, restricted to
     the 1.1a scope:
     from the site onward, inside ITS OWN statement block and descending into
     body/orelse/finalbody/handlers[].body/cases[].body (never ascending, never
     descending into a nested function/lambda/class), collect reachable
     `return` exits; a site is green iff none of them is an ERROR exit.
     `return <name>` / other non-literal forms are treated as ERROR (fail-closed,
     #1203 §二 P9).

Expected classification after 1.1a:
  GREEN (fixed/in-scope): 15  = 5 token-path (claim x3, ack, reset)
                              + 8 moved (create_thread x2, set_verdict,
                                bump_revision, set_quorum x2, request_form_b,
                                register_meta)
                              + 2 already-compliant (:heartbeat_and_recompute,
                                list_comments_since)
  RED, explicitly OUT OF SCOPE (#1177 §五): 3 = post_comment, reply_comment,
      set_status (budget/human faces — batch 4, not 1.1a)

Check 4 (gate-4, #1212 P14 / #1216 §二): the locator's "never ascend" premise is only
valid while the three token functions contain no `try`/`except`/`finally`.
AST-enumerate Try|TryStar inside claim_token / ack_token / reset_token and
require zero (today zero).  A line regex is NOT sufficient: `except*` (PEP 654)
has no whitespace after `except`, so the natural `except\s` spelling misses it
(`^\s*(try|except|finally)\b` happens to catch it, #1277 §二 — the reason to
enumerate the AST is that a line regex is also blind to `try` inside a string or
comment and cannot attribute a `try` to its enclosing function).  `--self-test`
proves this gate can go red on a synthetic function — for BOTH node kinds
(`try` and `except*`): a gate that is always green has no discriminating power.

Exit 0 only when the counts match, the red set is exactly those 3, and gate-4
is clean.
"""
import ast
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "server.py"
OUT_OF_SCOPE = {"post_comment", "reply_comment", "set_status"}
TOKEN_SCOPE = {"claim_token", "ack_token", "reset_token"}
HAS_TRYS = sys.version_info >= (3, 11)  # PEP 654 / ast.TryStar


def head_is_error(value: ast.AST | None) -> bool:
    """Leftmost text of a return expression; unknown forms => ERROR (fail-closed).

    Handles the three frozen shapes: plain `return "ERROR…"`, f-string
    `return f"ERROR…"`, multi-line implicit concatenation (`BinOp(Add)` chains of
    Constant/JoinedStr), and `return <name>` / `return call(...)`.
    """
    if value is None:
        return False
    if isinstance(value, ast.Constant) and isinstance(value.value, str):
        return value.value.startswith("ERROR")
    if isinstance(value, ast.JoinedStr):
        for v in value.values:
            if isinstance(v, ast.Constant) and isinstance(v.value, str):
                return v.value.startswith("ERROR")
            # First segment is an expression => leftmost text is unprovable.
            # Contract choice (a), thread #91 dsh #1277 §三: unprovable => ERROR,
            # same as `return <name>`/`return call(...)` below.  The other choice
            # (b) would judge `return f"{x}"` as NON-error while `return x` is
            # ERROR — two opposite verdicts for the same unprovable shape, and a
            # gate that lets an unprovable exit count as green.
            return True
        return False
    if isinstance(value, ast.BinOp) and isinstance(value.op, ast.Add):
        return head_is_error(value.left)
    return True  # name/call/other => fail-closed


def enclosing_func(tree: ast.AST) -> dict:
    owner = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for child in ast.walk(node):
                owner.setdefault(id(child), node.name)
    return owner


def parents(tree: ast.AST) -> dict:
    p = {}
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            p[id(child)] = node
    return p


# Statement lists a site can be a DIRECT child of.  Function/class bodies are
# anchors in their own right (see owning_blocks); they are NOT descended into by
# reachable_returns (a nested `def`'s `return` is not reachable from the site).
OWN_BODY = (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)


def block_children(stmt: ast.stmt) -> list[list[ast.stmt]]:
    """The statement lists reachable by DESCENDING from `stmt` (not ascending)."""
    out = []
    if isinstance(stmt, ast.If):
        out += [stmt.body, stmt.orelse]
    elif isinstance(stmt, (ast.For, ast.AsyncFor, ast.While)):
        out += [stmt.body, stmt.orelse]
    elif isinstance(stmt, (ast.With, ast.AsyncWith)):
        out += [stmt.body]
    elif isinstance(stmt, ast.Try) or type(stmt).__name__ == "TryStar":
        out.append(stmt.body)
        for h in stmt.handlers:
            out.append(h.body)
        out.append(stmt.orelse)
        out.append(stmt.finalbody)
    elif isinstance(stmt, ast.Match):
        out += [c.body for c in stmt.cases]
    return out


def owning_blocks(parent: ast.AST) -> list[list[ast.stmt]]:
    """Statement lists in which `parent` directly owns a child statement.

    Function/class bodies must be anchors of their own: a site sitting directly
    in a function body has to be judged against THAT body.  Without them the
    climb stops at `Module.body`, `idx` points at the `def`, and
    `reachable_returns` scans module-level statements — where `return` is a
    syntax error — so `bad` is forever empty and the site is structurally green
    (thread #91 §二, P16-class false green).  The old `DESCEND` constant was
    defined but never read, so editing it had zero effect (claude #1270).
    """
    if isinstance(parent, OWN_BODY):
        return [parent.body]
    return block_children(parent)


def locate(site: ast.AST, par: dict) -> tuple[list[ast.stmt] | None, int | None]:
    """The (statement list, index) that directly owns `site` — never ascending
    past the innermost function/class/module body.  (None, None) if unplaceable."""
    cur = site
    while id(cur) in par:
        parent = par[id(cur)]
        for lst in owning_blocks(parent):
            if any(s is cur for s in lst):
                return lst, lst.index(cur)
        cur = parent
    return None, None


def reachable_returns(stmts: list[ast.stmt], start: int) -> list[ast.Return]:
    found = []
    for st in stmts[start:]:
        if isinstance(st, ast.Return):
            found.append(st)
            continue
        for child in block_children(st):
            found += reachable_returns(child, 0)
    return found


def gate4_failures(tree: ast.AST) -> list[tuple[str, int]]:
    """Try/TryStar inside the three token functions: locator premise (P14)."""
    bad = []
    try_nodes = (ast.Try,) + ((ast.TryStar,) if hasattr(ast, "TryStar") else ())
    for node in ast.walk(tree):
        if (isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                and node.name in TOKEN_SCOPE):
            for child in ast.walk(node):
                if isinstance(child, try_nodes):
                    bad.append((node.name, child.lineno))
    return bad


def red_by_function(tree: ast.AST) -> list[str]:
    """Check-2 classification over a parsed tree: enclosing functions judged RED."""
    par = parents(tree)
    owner = enclosing_func(tree)
    red = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "_touch" and node.args
                and isinstance(node.args[0], ast.Name)
                and node.args[0].id == "conn"):
            continue
        stmts, idx = locate(node, par)
        if stmts is None:
            red.append("<no enclosing block>")
            continue
        if any(head_is_error(r.value) for r in reachable_returns(stmts, idx + 1)):
            red.append(owner.get(id(node), "?"))
    return sorted(set(red))


def self_test() -> int:
    """Prove both gates can report red (a gate that never fires is not a gate)."""
    ok = True
    g4_cases = [
        ("def claim_token():\n    try:\n        return 'x'\n"
         "    except Exception:\n        return 'ERROR: x'\n", 1),
        ("def claim_token():\n    return 'x'\n", 0),
        ("def unrelated():\n    try:\n        return 'x'\n"
         "    except Exception:\n        return 'y'\n", 0),
        # TryStar / `except*` half (PEP 654): the ONLY node kind a line regex can
        # plausibly miss, and the reason this gate is AST-based at all.  Without
        # this case, deleting `ast.TryStar` from gate4_failures leaves the whole
        # self-test green => that half of the gate has no discriminating power
        # (#1277 §二).  `return` is legal in the try body, not in an `except*`
        # clause (PEP 654 forbids return/break/continue there — compile-checked).
        ("def claim_token():\n    try:\n        return 'ERROR: x'\n"
         "    except* ValueError:\n        pass\n", 1),
    ]
    for src, want in g4_cases:
        if not HAS_TRYS and "except*" in src:
            # PEP 654 (TryStar / `except*`) is 3.11+ syntax: on 3.10 the source
            # would not even parse, so this case cannot run.  It must say SKIP,
            # never OK — a silently green half is exactly what #1277 §二 killed
            # (#1280 §一, gap C: the 3.10 floor and this gate must not disagree).
            print(f"self-test gate-4 want={want} got=SKIP(py<3.11)")
            continue
        got = len(gate4_failures(ast.parse(src)))
        good = got == want
        ok = ok and good
        print(f"self-test gate-4 want={want} got={got} {'OK' if good else 'FAIL'}")

    # check-2 self-test: a FUNCTION-BODY-level site must be judged against its own
    # body.  Case 1 is the blind spot itself (green before the FunctionDef anchor,
    # red after) — it proves both that the hole existed and that the fix closes it.
    loc_cases = [
        ("def heartbeat_and_recompute(conn):\n"
         "    _touch(conn, 'a')\n"
         "    return 'ERROR: x'\n", ["heartbeat_and_recompute"]),
        ("def heartbeat_and_recompute(conn):\n"
         "    _touch(conn, 'a')\n"
         "    return 'ok'\n", []),
        # nested def's ERROR return is NOT reachable from the site
        ("def heartbeat_and_recompute(conn):\n"
         "    _touch(conn, 'a')\n"
         "    def inner():\n"
         "        return 'ERROR: x'\n"
         "    return 'ok'\n", []),
        # an ERROR return BEFORE the site is not reachable
        ("def heartbeat_and_recompute(conn):\n"
         "    if conn:\n"
         "        return 'ERROR: x'\n"
         "    _touch(conn, 'a')\n"
         "    return 'ok'\n", []),
        # ERROR inside a `try` body after the site IS reachable
        ("def claim_token(conn):\n"
         "    _touch(conn, 'a')\n"
         "    try:\n"
         "        return 'ERROR: x'\n"
         "    except Exception:\n"
         "        return 'ok'\n", ["claim_token"]),
        # Same, but the node is a TryStar (`except*`): this is the case that
        # lights block_children()'s TryStar descent branch.  Dropping that branch
        # makes this case green => FAIL (previously: zero assertions on it).
        ("def claim_token(conn):\n"
         "    _touch(conn, 'a')\n"
         "    try:\n"
         "        return 'ERROR: x'\n"
         "    except* ValueError:\n"
         "        pass\n", ["claim_token"]),
        # Unprovable leftmost text is ERROR (fail-closed, choice (a)): an f-string
        # whose first segment is an expression must not read as green.
        ("def claim_token(conn):\n"
         "    _touch(conn, 'a')\n"
         "    return f'{conn} oops'\n", ["claim_token"]),
    ]
    for src, want in loc_cases:
        if not HAS_TRYS and "except*" in src:
            print(f"self-test check-2 want={want} got=SKIP(py<3.11)")
            continue
        got = red_by_function(ast.parse(src))
        good = got == want
        ok = ok and good
        print(f"self-test check-2 want={want} got={got} {'OK' if good else 'FAIL'}")

    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    src = SRC.read_text(encoding="utf-8")
    tree = ast.parse(src)
    owner = enclosing_func(tree)
    par = parents(tree)

    sites = []
    for node in ast.walk(tree):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "_touch" and node.args
                and isinstance(node.args[0], ast.Name) and node.args[0].id == "conn"):
            sites.append(node)
    sites.sort(key=lambda n: n.lineno)

    # ---- check 1: counts (occurrence semantics) ----
    # (sites[] above is the "AST site enumeration" half of check 2.)
    bare = len(re.findall(r"_touch\(conn", src))
    indented = len(re.findall(r"^\s+_touch\(conn", src, re.M))
    defline = len(re.findall(r"def _touch\(conn", src))
    spaced = len(re.findall(r"_touch\s+\(", src))
    print(f"counts: sites={len(sites)} bare={bare} indented={indented} "
          f"def={defline} spaced={spaced}")
    ok = (bare == len(sites) + 1 and indented == len(sites)
          and defline == 1 and bare - indented == 1 and spaced == 0)

    # ---- check 2: per-site mirror classification (d2″) ----
    red = []
    for site in sites:
        stmts, idx = locate(site, par)
        if stmts is None:
            print(f"  ?? line {site.lineno}: no enclosing block")
            ok = False
            continue
        bad = [r.lineno for r in reachable_returns(stmts, idx + 1) if head_is_error(r.value)]
        fname = owner.get(id(site), "?")
        verdict = "GREEN" if not bad else f"RED after={bad}"
        print(f"  line {site.lineno:5d}  {fname:24s} {verdict}")
        if bad:
            red.append(fname)

    scope_red = set(red) - OUT_OF_SCOPE
    unexpected_green = OUT_OF_SCOPE - set(red)
    print(f"red functions: {sorted(set(red))}")
    print(f"out-of-scope red (expected exactly {sorted(OUT_OF_SCOPE)}): {sorted(set(red) & OUT_OF_SCOPE)}")
    ok = ok and not scope_red and not unexpected_green

    # ---- check 4: locator premise (P14) ----
    g4 = gate4_failures(tree)
    print(f"gate-4 Try/TryStar in {sorted(TOKEN_SCOPE)}: {g4 or 'none'}")
    ok = ok and not g4
    print("RESULT:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
